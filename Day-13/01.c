// ************ARRAY SORTING (Selection sort)***************

#include<stdio.h>
#include<stdlib.h>
#include<unistd.h>
#include<pthread.h>

void swap(int *a,int *b){
	int temp = *a;
	*a = *b;
	*b = temp;
}

void* selection_sort(void* arr){
	int*ptr = (int*)arr;
	int i,j,min_idx;
	for( i=0; i<9; i++ ){
		min_idx = i;
		for(j=i+1; j<10; j++){
			if(ptr[j]<ptr[i]){
			min_idx = j;}
		}
		if(min_idx!=i) // if arr[j] is greater, min_idx = i
			swap(&ptr[min_idx],&ptr[i]);
	} 	
	return NULL;
}

int main(){

	pthread_t t;
	int arr[10];
	printf("Enter 10 integers :");
	for(int i=0; i<10; i++){
		scanf("%d",&arr[i]);
	}
	int ret = pthread_create(&t,NULL,selection_sort,arr);
	if(ret!=0){
		perror("Thread creation failed\n");
		exit(-1);
	}
	pthread_join(t,NULL);
	printf("Sorted array :");
	for(int i=0; i<10; i++)
		printf(" %d",arr[i]);
	printf("\n");
return 0;}







































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































